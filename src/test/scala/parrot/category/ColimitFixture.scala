/** Samples of the apex of a colimit of shape **2** in 𝒮, whatever its type: its points are made and observed through
  * the colimit itself.
  */
object ColimitSamples {
  import Category.Discrete2
  import Coproduct.CopairCocone

  /** Points of the colimit, generated by the legs of the colimit, and varied and compared through the factorization
    * of the cocone of the two injections of a tagged union.
    */
  def apex(colimit: Colimit { val diagram: Functor.Into[Total.type] { val source: Discrete2.type } })(
    using
    first: Sample[colimit.diagram.F[0]],
    second: Sample[colimit.diagram.F[1]],
  ): Sample[colimit.X] = {
    type Union = Either[colimit.diagram.F[0], colimit.diagram.F[1]]
    val unions                      = Sample.EitherSample(using first, second)
    val tagged: colimit.X -> Union = {
      colimit.factor(CopairCocone(colimit.diagram, Total.Object[Union])(a => Left(a), b => Right(b)))
    }
    val points = unions.gen.map(_.fold(colimit.leg[0], colimit.leg[1]))
    val equality: colimit.X is Eq = new Eq {
      type Self = colimit.X

      def equal(x: colimit.X, y: colimit.X): Boolean = {
        unions.eq.equal(tagged(x), tagged(y))
      }
    }
    Sample(points, unions.cogen.contramap(tagged), equality)
  }
}

/** Colimits of the discrete 2-object diagram (`Int`,`String`) in 𝒮, each as a stable value. */
object IntStringColimits {
  import Coproduct.CopairCocone

  /** The diagram (`Int`,`String`). */
  val diagram = IntStringLimits.diagram

  /** A cocone under the diagram with apex `Long`. */
  val cocone = CopairCocone(diagram, Total.Object[Long])((n: Int) => n.toLong, (s: String) => s.length.toLong)

  /** The colimit by abstraction: points tagged with their object. */
  val byAbstraction = Total.ColimitOf(diagram)

  /** The colimit by abstraction, as one of the colimits of every diagram in 𝒮. */
  val amongAll = Total.Colimits.colimit(diagram)

  /** The colimit of a discrete shape: sums of points. */
  val discrete = Total.DiscreteColimitOf(diagram)

  /** The tagged union, a coproduct, as a colimit. */
  val unions = Total.EitherIsCoproduct[Int, String]().asColimit
}
