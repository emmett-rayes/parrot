object LimitCartesian extends Cartesian(Total, LimitTerminal, LimitProducts)

/** Samples of the apex of a limit of shape **2** in 𝒮, whatever its type: its points are made and observed through
  * the limit itself.
  */
object LimitSamples {
  import Category.Discrete2
  import Product.PairCone

  /** Points of the limit, generated by factoring the cones of two constant legs, and varied and compared through the
    * legs of the limit.
    */
  def apex(limit: Limit { val diagram: Functor.Into[Total.type] { val source: Discrete2.type } })(
    using
    first: Sample[limit.diagram.F[0]],
    second: Sample[limit.diagram.F[1]],
  ): Sample[limit.X] = {
    val legs: limit.X -> (limit.diagram.F[0], limit.diagram.F[1]) = x => (limit.leg[0](x), limit.leg[1](x))
    val pairs                                                      = Sample.Tuple2Sample(using first, second)
    val points                                                     = pairs.gen.map { (a, b) =>
      limit.factor(PairCone(limit.diagram, Total.Object[Unit])(_ => a, _ => b))(())
    }
    val equality: limit.X is Eq = new Eq {
      type Self = limit.X

      def equal(x: limit.X, y: limit.X): Boolean = {
        pairs.eq.equal(legs(x), legs(y))
      }
    }
    Sample(points, pairs.cogen.contramap(legs), equality)
  }
}

/** Limits of the discrete 2-object diagram (`Int`,`String`) in 𝒮, each as a stable value. */
object IntStringLimits {
  import Product.{Discrete2Diagram, PairCone}

  /** The diagram (`Int`,`String`). */
  val diagram = Discrete2Diagram(Total, Total.Object[Int], Total.Object[String])

  /** A cone over the diagram with apex `Long`. */
  val cone = PairCone(diagram, Total.Object[Long])((n: Long) => (n % 1000).toInt, (n: Long) => n.toString)

  /** The limit by abstraction: natural families of points. */
  val byAbstraction = Total.LimitOf(diagram)

  /** The limit by abstraction, as one of the limits of every diagram in 𝒮. */
  val amongAll = Total.Limits.limit(diagram)

  /** The limit of a discrete shape: families of points. */
  val discrete = Total.DiscreteLimitOf(diagram)

  /** The pair type, a product, as a limit. */
  val pairs = Total.Tuple2IsProduct[Int, String]().asLimit
}
